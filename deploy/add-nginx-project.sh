#!/usr/bin/env bash
set -Eeuo pipefail

usage() {
  printf 'usage: sudo %s <project-name> <port>\n' "$0" >&2
  exit 2
}

[[ $# -eq 2 ]] || usage
name=$1
port=$2
[[ "$name" =~ ^[a-z0-9][a-z0-9-]*$ ]] || {
  printf 'invalid project name: use lowercase letters, digits, and dashes\n' >&2
  exit 2
}
[[ "$port" =~ ^[0-9]{1,5}$ ]] && ((10#$port >= 1 && 10#$port <= 65535)) || {
  printf 'invalid port\n' >&2
  exit 2
}
[[ "$(id -u)" -eq 0 ]] || {
  printf 'run this helper through sudo\n' >&2
  exit 1
}

site=/etc/nginx/sites-available/default
snippet=/etc/nginx/snippets/projects-$name.conf
include="    include $snippet;"

cat >"$snippet" <<EOF
# Mounts an SPA at /projects/$name/ and strips the prefix before proxying,
# so the upstream still serves its app and API from /. Generated by
# deploy/add-nginx-project.sh; safe to edit or remove.
location = /projects/$name {
    return 308 /projects/$name/;
}

location ^~ /projects/$name/ {
    proxy_pass http://127.0.0.1:$port/;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto \$scheme;
}
EOF

if ! grep -Fqx "$include" "$site"; then
  backup=$(mktemp)
  cp -p "$site" "$backup"
  trap 'cp -p "$backup" "$site"; rm -f "$backup"' ERR
  python3 - "$site" "$include" <<'PY'
import sys

path, include = sys.argv[1], sys.argv[2]
with open(path, "r", encoding="utf-8") as handle:
    lines = handle.readlines()

out = []
inserted = False
for line in lines:
    out.append(line)
    stripped = line.strip()
    if not inserted and stripped.startswith("listen 443") and "ssl" in stripped:
        out.append(include + "\n")
        inserted = True

if not inserted:
    sys.exit("could not find a 'listen 443 ssl' server block in " + path)

with open(path, "w", encoding="utf-8") as handle:
    handle.write("".join(out))
PY
  rm -f "$backup"
  trap - ERR
fi

nginx -t
systemctl reload nginx
printf 'Serving https://jarldev.com/projects/%s/ from 127.0.0.1:%s\n' "$name" "$port"
